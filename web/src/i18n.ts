export function getLanguageMode(): LanguageMode {
  const value = localStorage.getItem(KEY);
  return value === "zh" || value === "en" ? value : "system";
}
/** Mirror the UI language into the native layer so tool results match it. */
function pushLanguageToNative(mode: LanguageMode): void {
  try {
    window.AndroidBridge?.setUiLanguage?.(mode);
  } catch {
    /* browser preview: no bridge */
  }
}
/** Push the stored language on startup (the native side defaults to the system locale). */
export function syncLanguageToNative(): void {
  pushLanguageToNative(getLanguageMode());
}
export function setLanguageMode(mode: LanguageMode): void {
  localStorage.setItem(KEY, mode);
  pushLanguageToNative(mode);
  window.dispatchEvent(new Event("andagent:language"));
}
export function currentLanguage(): "zh" | "en" {
  const mode = getLanguageMode();
  return mode === "system" ? (navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en") : mode;
}
const subscribe = (listener: () => void) => {
  window.addEventListener("andagent:language", listener);
  return () => window.removeEventListener("andagent:language", listener);
};
export function translate(key: Key, params?: Record<string, string | number>): string {
  const value = currentLanguage() === "zh" ? zh[key] : en[key];
  return params ? value.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match)) : value;
}

export function useI18n() {
  const language = useSyncExternalStore(subscribe, currentLanguage, () => "en" as const);
  return { language, mode: getLanguageMode(), t: (key: Key, params?: Record<string, string | number>) => { const value = language === "zh" ? zh[key] : en[key]; return params ? value.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match)) : value; } };
}
