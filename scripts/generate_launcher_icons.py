#!/usr/bin/env python3
"""Generate every Android launcher icon asset from design/andagent-icon.svg.

The SVG is the single source of truth. This script converts it into:

  * res/drawable/ic_launcher_background.xml   <shape> gradient (adaptive bg layer)
  * res/drawable/ic_launcher_foreground.xml   <vector> white mark (adaptive fg layer)
  * res/drawable/ic_stat_andagent.xml         <vector> 24dp notification small icon
  * res/mipmap-anydpi-v26/ic_launcher{,_round}.xml   adaptive icon descriptors
  * res/mipmap-*/ic_launcher{,_round}.png    legacy launcher fallbacks
  * design/andagent-icon-512.png             Google Play listing icon
  * design/andagent-icon-preview.png         circular-mask preview

Usage:  python3 scripts/generate_launcher_icons.py
Requires: rsvg-convert (macOS: brew install librsvg)
"""

from __future__ import annotations

import copy
import math
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import quoteattr

SVG_NS = "http://www.w3.org/2000/svg"
ANDROID_NS = "http://schemas.android.com/apk/res/android"
ET.register_namespace("", SVG_NS)

ROOT = Path(__file__).resolve().parent.parent
SVG_FILE = ROOT / "design" / "andagent-icon.svg"
RES = ROOT / "app" / "src" / "main" / "res"
DESIGN = ROOT / "design"

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

# SVG paint attribute -> VectorDrawable <path> attribute
PATH_ATTRS = {
    "fill": "fillColor",
    "fill-opacity": "fillAlpha",
    "fill-rule": "fillType",
    "stroke": "strokeColor",
    "stroke-opacity": "strokeAlpha",
    "stroke-width": "strokeWidth",
    "stroke-linecap": "strokeLineCap",
    "stroke-linejoin": "strokeLineJoin",
    "stroke-miterlimit": "strokeMiterLimit",
}
IGNORED_ATTRS = {"id"}


def q(tag: str) -> str:
    return f"{{{SVG_NS}}}{tag}"


def attr(name: str, value: str) -> str:
    return f"android:{name}={quoteattr(value)}"


def generated_header() -> str:
    return ("<!-- Generated by scripts/generate_launcher_icons.py "
            "from design/andagent-icon.svg. Do not edit. -->\n")


def collect_paths(node: ET.Element, inherited: dict[str, str] | None = None):
    """Yield (pathData, paint attrs), inheriting paints from parent <g>."""
    merged = dict(inherited or {})
    merged.update({k: v for k, v in node.attrib.items() if k != "d"})
    if node.tag == q("path"):
        yield node.get("d", ""), merged
    for child in node:
        yield from collect_paths(child, merged)


def paint_attrs(paint: dict[str, str]) -> str:
    parts = []
    for key, value in paint.items():
        if key in IGNORED_ATTRS:
            continue
        if key not in PATH_ATTRS:
            raise ValueError(f"unsupported SVG attribute in icon mark: {key}={value}")
        if value == "none":
            continue
        android_name = PATH_ATTRS[key]
        if key == "fill-rule":
            value = "evenOdd" if value == "evenodd" else "nonZero"
        parts.append(attr(android_name, value))
    return ("\n        " + " ".join(parts)) if parts else ""


def vector_xml(paths, viewport: int, size_dp: int) -> str:
    body = "".join(
        f'    <path {attr("pathData", data)}{paint_attrs(paint)} />\n'
        for data, paint in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + generated_header()
        + f'<vector xmlns:android="{ANDROID_NS}"\n'
        + f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
        + f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
        + body
        + "</vector>\n"
    )


def background_xml(root: ET.Element) -> str:
    rect = root.find(f"{q('rect')}[@id='background']")
    if rect is None:
        raise ValueError("expected <rect id=\"background\"> in the SVG")
    fill = rect.get("fill", "")
    if not fill.startswith("url("):
        if not fill.startswith("#"):
            raise ValueError(f"unsupported background fill: {fill}")
        body = f'    <solid android:color="{fill.upper()}" />\n'
    else:
        grad = root.find(f"{q('defs')}/{q('linearGradient')}")
        if grad is None or grad.get("id") != "bg":
            raise ValueError("expected <linearGradient id=\"bg\"> in the SVG")
        if grad.get("gradientUnits", "objectBoundingBox") != "userSpaceOnUse":
            raise ValueError("bg gradient must use gradientUnits=\"userSpaceOnUse\"")

        stops = [(float(s.get("offset", "0").rstrip("%")), s.get("stop-color"))
                 for s in grad.findall(q("stop"))]
        if len(stops) not in (2, 3) or any(c is None for _, c in stops):
            raise ValueError("bg gradient needs 2 or 3 opaque color stops")

        x1, y1 = float(grad.get("x1", "0")), float(grad.get("y1", "0"))
        x2, y2 = float(grad.get("x2", "1")), float(grad.get("y2", "1"))
        angle = int(round(math.degrees(math.atan2(-(y2 - y1), x2 - x1)) / 45) * 45) % 360

        colors = " ".join(
            attr(name, color)
            for name, (_, color) in zip(("startColor", "centerColor", "endColor")
                                        if len(stops) == 3 else ("startColor", "endColor"),
                                        stops)
        )
        body = f'    <gradient android:type="linear" android:angle="{angle}" {colors} />\n'
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + generated_header()
        + f'<shape xmlns:android="{ANDROID_NS}" android:shape="rectangle">\n'
        + body
        + "</shape>\n"
    )


def adaptive_xml() -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + generated_header()
        + f'<adaptive-icon xmlns:android="{ANDROID_NS}">\n'
        + '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        + '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        + "</adaptive-icon>\n"
    )


def variant_svg(root: ET.Element, view_box: str, circle_radius: float | None) -> bytes:
    """Copy the SVG, optionally crop in and apply a circular clip (round icons)."""
    doc = copy.deepcopy(root)
    doc.set("viewBox", view_box)
    if circle_radius is None:
        return ET.tostring(doc, encoding="utf-8", xml_declaration=True)

    defs = doc.find(q("defs"))
    clip = ET.SubElement(defs, q("clipPath"), {"id": "round-clip"})
    ET.SubElement(clip, q("circle"), {"cx": "54", "cy": "54", "r": str(circle_radius)})
    masked = ET.Element(q("g"), {"clip-path": "url(#round-clip)"})
    for child in list(doc):
        if child.tag != q("defs"):
            doc.remove(child)
            masked.append(child)
    doc.append(masked)
    return ET.tostring(doc, encoding="utf-8", xml_declaration=True)


def render(svg_bytes: bytes, output: Path, size: int, tmp_dir: Path) -> None:
    src = tmp_dir / f"{output.stem}-{size}.svg"
    src.write_bytes(svg_bytes)
    output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["rsvg-convert", "-w", str(size), "-h", str(size), "-o", str(output), str(src)],
        check=True,
    )


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  {path.relative_to(ROOT)}")


def main() -> int:
    if not SVG_FILE.is_file():
        print(f"missing source SVG: {SVG_FILE}", file=sys.stderr)
        return 1
    if shutil.which("rsvg-convert") is None:
        print("rsvg-convert not found; install it with: brew install librsvg", file=sys.stderr)
        return 1

    root = ET.parse(SVG_FILE).getroot()
    mark = root.find(f".//{q('g')}[@id='mark']")
    notification = root.find(f".//{q('g')}[@id='notification']")
    if mark is None or notification is None:
        print("SVG needs <g id=\"mark\"> and <g id=\"notification\">", file=sys.stderr)
        return 1

    print("Android resources:")
    write(RES / "drawable" / "ic_launcher_background.xml", background_xml(root))
    write(RES / "drawable" / "ic_launcher_foreground.xml",
          vector_xml(list(collect_paths(mark)), viewport=108, size_dp=108))
    write(RES / "drawable" / "ic_stat_andagent.xml",
          vector_xml(list(collect_paths(notification)), viewport=24, size_dp=24))
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        write(RES / "mipmap-anydpi-v26" / name, adaptive_xml())

    # Legacy PNGs are cropped in (viewBox 12..96) so the mark is not tiny on
    # launchers that do not support adaptive icons.
    square = variant_svg(root, "12 12 84 84", None)
    round_ = variant_svg(root, "12 12 84 84", 42)
    full = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    preview = variant_svg(root, "0 0 108 108", 54)

    print("PNG assets:")
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        for density, size in DENSITIES.items():
            folder = RES / f"mipmap-{density}"
            for name, svg in (("ic_launcher.png", square), ("ic_launcher_round.png", round_)):
                out = folder / name
                render(svg, out, size, tmp_dir)
                print(f"  {out.relative_to(ROOT)}")
        for name, svg in (("andagent-icon-512.png", full),
                          ("andagent-icon-preview.png", preview)):
            out = DESIGN / name
            render(svg, out, 512, tmp_dir)
            print(f"  {out.relative_to(ROOT)}")

    print("Done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
